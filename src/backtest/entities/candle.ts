/**
 * OHLCV Candle data structure
 */
export interface Candle {
  timestamp: number; // Unix timestamp in milliseconds
  open: number;
  high: number;
  low: number;
  close: number;
  volume: number;
}

/**
 * Supported timeframe intervals
 */
export type Timeframe =
  | '1m'
  | '3m'
  | '5m'
  | '15m'
  | '30m'
  | '1h'
  | '2h'
  | '4h'
  | '6h'
  | '8h'
  | '12h'
  | '1d'
  | '3d'
  | '1w'
  | '1M';

/**
 * Request parameters for fetching candles
 */
export interface CandleRequest {
  symbol: string; // e.g., 'BTCUSDT'
  timeframe: Timeframe;
  startTime?: number; // Unix timestamp in ms
  endTime?: number; // Unix timestamp in ms
  limit?: number; // Max 1000 per request
}

/**
 * Trade signal generated by an indicator
 */
export enum Signal {
  Buy = 'BUY',
  Sell = 'SELL',
  Hold = 'HOLD',
}

/**
 * A single trade in the backtest
 */
export interface Trade {
  entryTime: number;
  entryPrice: number;
  exitTime?: number;
  exitPrice?: number;
  side: 'long' | 'short';
  size: number;
  pnl?: number;
  pnlPercent?: number;
}

/**
 * Backtest configuration
 */
export interface BacktestConfig {
  symbol: string;
  timeframe: Timeframe;
  startTime?: number;
  endTime?: number;
  initialCapital: number;
  positionSizePercent: number; // Percentage of capital per trade (0-100)
  commission: number; // Commission per trade as decimal (e.g., 0.001 = 0.1%)
  slippage: number; // Slippage as decimal (e.g., 0.001 = 0.1%)
}

/**
 * Backtest performance results
 */
export interface BacktestResult {
  config: BacktestConfig;
  trades: Trade[];
  metrics: BacktestMetrics;
  equityCurve: { timestamp: number; equity: number }[];
}

/**
 * Performance metrics from a backtest
 */
export interface BacktestMetrics {
  totalTrades: number;
  winningTrades: number;
  losingTrades: number;
  winRate: number;
  totalPnl: number;
  totalPnlPercent: number;
  averageWin: number;
  averageLoss: number;
  largestWin: number;
  largestLoss: number;
  profitFactor: number;
  maxDrawdown: number;
  maxDrawdownPercent: number;
  sharpeRatio: number;
  sortinoRatio: number;
  averageHoldingPeriod: number; // in milliseconds
}

/**
 * Indicator strategy interface - implement this to create custom strategies
 */
export interface IndicatorStrategy {
  name: string;
  description: string;

  /**
   * Initialize the indicator with any required parameters
   */
  init?(params: Record<string, any>): void;

  /**
   * Calculate the signal for the current candle
   * @param candles - Array of candles up to and including current
   * @param index - Current candle index
   * @returns Trading signal
   */
  calculate(candles: Candle[], index: number): Signal;

  /**
   * Optional: Get indicator values for visualization/debugging
   */
  getIndicatorValues?(candles: Candle[], index: number): Record<string, number>;
}
